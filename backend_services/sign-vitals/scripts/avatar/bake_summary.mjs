// Writes BAKE_SUMMARY.md from the latest direct-solver bake reports
// (extracted/<sign>.direct.bake_report.json), the extractions (hand
// detection) and the committed motion files (size).
//   node bake_summary.mjs
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const EXTRACTED = path.join(HERE, "extracted");
const MOTION_DIR = path.resolve(HERE, "../../../../frontend/src/modules/sign-vitals/assets/motion");

const signs = fs.readdirSync(EXTRACTED).filter((f) => f.endsWith(".direct.bake_report.json")).map((f) => f.split(".")[0]).sort();
const worst = (r, part) => {
  const v = ["left", "right"].map((s) => r.fk_error_final[`${s}${part}`]?.mean_deg).filter((x) => x != null);
  return v.length ? Math.max(...v) : null;
};
const deg = (x) => (x == null ? "–" : `${Math.round(x)}°`);
const median = (xs) => { const s = xs.filter((x) => x != null).sort((a, b) => a - b); return s[Math.floor(s.length / 2)]; };

const rows = [];
for (const sign of signs) {
  const r = JSON.parse(fs.readFileSync(path.join(EXTRACTED, `${sign}.direct.bake_report.json`), "utf8"));
  const ex = JSON.parse(zlib.gunzipSync(fs.readFileSync(path.join(EXTRACTED, `${sign}.json.gz`))));
  const pct = (k) => Math.round((100 * ex.frames.filter((f) => f[k]).length) / ex.frames.length);
  const motion = JSON.parse(fs.readFileSync(path.join(MOTION_DIR, `${sign}.json`), "utf8"));
  const rested = motion.quality_flags.filter((f) => f.type === "arm_rested").reduce((s, f) => s + f.frames[1] - f.frames[0] + 1, 0);
  const limited = r.joint_limits?.frames_limited ?? 0;
  const groups = Object.entries(r.joint_limits?.by_group ?? {}).sort((a, b) => b[1] - a[1]).map(([g, n]) => `${g} ${n}`).join(", ") || "–";
  rows.push({ sign, frames: r.frames, det: `${pct("left_hand_world")} / ${pct("right_hand_world")}`,
    hand: worst(r, "Hand"), finger: worst(r, "IndexIntermediate"),
    limited: `${limited} (${Math.round((100 * limited) / r.frames)}%)`, groups, rested, kb: Math.round(r.bytes / 1024) });
}

const lines = [
  "# Direct-solver bake: per-sign summary",
  "",
  "Generated by `node bake_summary.mjs`. Worst side, mean angle between baked and MediaPipe-measured bone direction (agreement with MediaPipe, not ground truth). Hand err = palm direction; finger err = index middle segment; both only on frames where that hand was detected. Hand smoothing 0.65, joint limits on, hips and lower spine upright (chest ≤ 10°, head ≤ 20°), arms eased to rest where the hand is missing and the wrist is out of view at the clip start / end (\"arm rested\", arm-frames).",
  "",
  `Medians: hand err ${deg(median(rows.map((r) => r.hand)))}, finger err ${deg(median(rows.map((r) => r.finger)))}; ${rows.filter((r) => r.rested > 0).length} signs with resting arms.`,
  "",
  "| sign | frames | L / R hand det. % | hand err | finger err | frames limited (of total) | limited groups | arm rested | KB |",
  "|---|---|---|---|---|---|---|---|---|",
  ...rows.map((r) => `| ${r.sign} | ${r.frames} | ${r.det} | ${deg(r.hand)} | ${deg(r.finger)} | ${r.limited} | ${r.groups} | ${r.rested} | ${r.kb} |`),
  "",
];
fs.writeFileSync(path.join(HERE, "BAKE_SUMMARY.md"), lines.join("\n"));
console.log(`BAKE_SUMMARY.md: ${rows.length} signs`);
