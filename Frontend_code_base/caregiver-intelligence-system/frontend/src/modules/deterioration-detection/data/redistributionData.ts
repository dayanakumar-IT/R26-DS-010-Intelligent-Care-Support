export function getLoadColor(load: number): string {
  if (load >= 85) return '#DC2626'
  if (load >= 70) return '#EA580C'
  if (load >= 55) return '#D97706'
  return '#16A34A'
}

export function getPriorityConfig(priority: 'urgent' | 'recommended' | 'optional') {
  const map = {
    urgent: {
      label: 'Urgent',
      bg: '#FEF2F2',
      text: '#DC2626',
      border: '#FECACA',
    },
    recommended: {
      label: 'Recommended',
      bg: '#FFF7ED',
      text: '#EA580C',
      border: '#FED7AA',
    },
    optional: {
      label: 'Optional',
      bg: '#F0FDF4',
      text: '#16A34A',
      border: '#BBF7D0',
    },
  }
  return map[priority]
}
